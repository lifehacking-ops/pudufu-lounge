-- 이미 돌아가는 DB(라이브)에 적용한다. db/schema.sql 은 DROP+CREATE 라 데이터를 지우므로
-- 라이브에는 이 파일을 쓴다 — psql "$DATABASE_URL"(5432 직접 연결) -v ON_ERROR_STOP=1 -f 이 파일.
--
-- 규칙
--   · 옛 표 · 컬럼(ext_week · ext_mission · lounge_week · post.week · lounge_member.week ·
--     ext_lesson.week/chapter/duration)은 지우지 않는다. 한 릴리스 뒤에 지운다.
--   · 확인 질의가 0 이 아니면 트랜잭션을 멈춘다(RAISE). 반쯤 옮긴 상태로 커밋되지 않는다.
--   · 과제(ext_mission)는 그 섹션의 **마지막 레슨**에 붙는다 — 주차를 다 듣고 내는 과제였다.
